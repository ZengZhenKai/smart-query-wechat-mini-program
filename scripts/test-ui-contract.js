'use strict'
const fs=require('fs'),path=require('path'),assert=require('assert')
const appJson=fs.readFileSync('miniprogram/app.json','utf8')
const app=JSON.parse(appJson)
const appWxss=fs.readFileSync('miniprogram/app.wxss','utf8')
const bootJs=fs.readFileSync('miniprogram/pages/boot/index.js','utf8')
const bootWxml=fs.readFileSync('miniprogram/pages/boot/index.wxml','utf8')
const registerWxml=fs.readFileSync('miniprogram/pages/register/index.wxml','utf8')
const registerWxss=fs.readFileSync('miniprogram/pages/register/index.wxss','utf8')
const profileWxss=fs.readFileSync('miniprogram/pages/profile/index.wxss','utf8')
const searchWxml=fs.readFileSync('miniprogram/pages/search/index.wxml','utf8')
const searchWxss=fs.readFileSync('miniprogram/pages/search/index.wxss','utf8')
assert.match(appJson,/#07C160/,'导航栏主色必须为微信绿')
assert.match(appWxss,/\.btn \{[^}]*background:#07c160/i,'全局主按钮必须使用微信绿')
assert.match(bootJs,/setTimeout\([\s\S]*1000\)/,'品牌启动页必须约1秒后进入原状态流程')
assert.match(bootWxml,/智慧查询/,'启动页必须居中显示智慧查询')
assert.match(profileWxss,/\.avatar-button\{[^}]*border-radius:50%[^}]*border:2rpx solid #07c160/i,'我的页头像必须为绿色细描边圆形头像')
assert.ok(!/test-phone|仅开发测试|OPENID/.test(registerWxml),'正式注册页不得包含测试入口或OPENID')
assert.match(searchWxml,/data-value="\{\{item\.testCode\}\}" data-field="testCode" bindtap="copy"/,'测试编码按钮必须复制当前卡片的testCode')
assert.match(searchWxml,/class="result-bottom"[\s\S]*data-value="\{\{item\.productName\}\}" data-field="productName" bindtap="copy"/,'右下角按钮必须复制当前卡片的productName')
assert.ok(!/<button[^>]*data-value="\{\{item\.assemblyCode\}\}"/.test(searchWxml),'总成编号不得增加复制按钮')
assert.match(searchWxss,/\.result-bottom\{[^}]*display:flex[^}]*align-items:flex-end[^}]*justify-content:space-between/i,'长短文本下复制按钮必须稳定处于独立底部区域右侧')
assert.match(searchWxss,/\.assembly-code\{[^}]*font-size:42rpx/i,'总成编号值必须使用更大字号')
assert.match(searchWxss,/\.assembly-code\{[^}]*font-weight:800/i,'总成编号值必须使用粗体')
assert.match(searchWxss,/\.assembly-code\{[^}]*color:#078848/i,'总成编号值必须使用绿色强调')
const formalPages=app.pages.filter(page=>page!=='pages/boot/index')
for(const page of formalPages){
  const file=path.join('miniprogram',`${page}.wxml`)
  assert.match(fs.readFileSync(file,'utf8'),/智慧查询，版权所有/,`${page}页面必须有版权页脚`)
}
console.log(`UI契约通过：微信绿主题、1秒品牌启动页、资料头像、查询结果复制布局及${formalPages.length}个正式页面版权页脚。`)
