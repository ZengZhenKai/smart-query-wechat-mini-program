'use strict'
const fs = require('fs')
const assert = require('assert')
const source = fs.readFileSync('cloudfunctions/api/index.js', 'utf8')
const security = fs.readFileSync('cloudfunctions/api/lib/security.js', 'utf8')
const superAdmin = fs.readFileSync('cloudfunctions/api/lib/super-admin.js', 'utf8')

assert.match(source, /assertSuperAdminBootstrapAllowed\(openid, process\.env\.SUPER_ADMIN_OPENIDS, testMode\)/, '初始化必须调用白名单安全模块')
assert.match(source, /ENABLE_SINGLE_SUPER_ADMIN_BOOTSTRAP/, '单超级管理员开发兼容开关必须与手机号注册解耦')
assert.ok(!source.includes('ENABLE_TEST_PHONE_REGISTRATION'), '超级管理员初始化不得继续依赖已删除的测试手机号模式')
assert.match(superAdmin, /allowlist\.length !== 2/, '生产模式超级管理员名单必须恰好两人')
assert.match(superAdmin, /unique\.size !== allowlist\.length/, '超级管理员名单必须去重')
assert.match(superAdmin, /!allowlist\.includes\(openid\)/, '名单外 OPENID 必须拒绝')
assert.match(source, /roles: \['super_admin'\]/, '管理员角色变更必须只允许 super_admin')
assert.match(source, /data\.role === 'admin'.*data\.role === 'user'/s, 'setAdminRole 只能接受 admin/user')
assert.match(source, /target\.role === 'super_admin'\) throw new Error\('不能修改超级管理员'\)/, 'setAdminRole 必须保护 super_admin')
assert.match(source, /target\.role === 'super_admin'\) throw new Error\('不能删除超级管理员'\)/, '删除接口必须保护 super_admin')
assert.match(source, /actor\.role !== 'super_admin' && target\.role !== 'user'/, '普通管理员只能操作普通员工')
assert.match(source, /cloud\.getWXContext\(\)/, '必须从微信上下文获取 OPENID')
assert.match(security, /user\.status !== 'approved'/, '受保护接口必须检查 approved 状态')
assert.ok(!source.includes('testCode: target.testCode'), '删除日志不得复制完整测试编码')
assert.ok(!source.includes('testCode: old.testCode'), '修改日志不得复制旧测试编码')
console.log('安全契约检查通过：超级管理员保护、服务端身份/状态/角色检查及日志最小化。')
