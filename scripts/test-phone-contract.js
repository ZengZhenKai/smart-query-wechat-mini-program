'use strict'
const fs=require('fs'),assert=require('assert')
const wxml=fs.readFileSync('miniprogram/pages/register/index.wxml','utf8')
const page=fs.readFileSync('miniprogram/pages/register/index.js','utf8')
const cloud=fs.readFileSync('cloudfunctions/api/index.js','utf8')
assert.match(wxml,/maxlength="4"[^>]*bindinput="onEmployeeCode"/,'注册页必须提供受长度限制的员工编号输入框')
assert.ok(page.includes('/^(?!000)\\d{3}$/.test(employeeCode)'),'前端必须校验001至999的三位员工编号')
assert.match(page,/const registerData = \{ name \}/,'注册请求必须使用最小资料对象')
assert.match(page,/registerData\.employeeCode = employeeCode/,'普通注册必须提交员工编号')
assert.match(page,/call\('register', registerData\)/,'前端必须向注册接口提交受控注册参数')
assert.match(page,/call\('session',[\s\S]*session\.registered[\s\S]*routeBySession/,'注册异常后必须复查session并按服务端状态路由')
assert.match(page,/showModal\(\{ title:'注册未完成', content:message/,'确认注册失败时必须显示完整错误')
assert.match(cloud,/normalizeEmployeeCode\(data\.employeeCode\)/,'服务端必须规范化员工编号')
assert.match(cloud,/where\(\{ openid \}\)\.limit\(1\)\.get\(\)/,'服务端必须检查OPENID唯一性')
assert.match(cloud,/where\(\{ employeeCode \}\)\.limit\(1\)\.get\(\)/,'服务端必须检查员工编号唯一性')
assert.match(cloud,/openid, name, nickname:name, employeeCode:/,'users必须保存最小注册资料')
assert.match(cloud,/log\(user, 'register'/,'正式注册必须记录最小化操作日志')
assert.match(cloud,/if \(old\.data\.length\) return \{ status: old\.data\[0\]\.status, alreadyRegistered: true \}/,'同一OPENID重复调用注册必须幂等返回当前状态')
assert.match(cloud,/catch \(err\) \{[\s\S]*register_log_error/,'用户写入成功后日志失败不得把注册伪装成失败')
const runtime=[wxml,page,cloud].join('\n')
assert.ok(!/getPhoneNumber|bindgetphonenumber|phoneToken|PHONE_TOKEN_SECRET/.test(runtime),'正式运行时不得残留微信手机号授权依赖')
assert.ok(!/仅开发测试|正式上线前必须关闭|OPENID/.test(wxml),'注册正式页面不得展示测试入口、OPENID或开发提示')
console.log('员工编号注册契约通过：前后端校验、编号/OPENID唯一、无手机号授权依赖。')
